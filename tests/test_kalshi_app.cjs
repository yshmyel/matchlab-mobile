const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const elements=new Map(),storage=new Map(),timers=[];
storage.set('matchlab_kalshi_cache_v1',JSON.stringify({schema_version:1,generated_utc:new Date().toISOString(),markets:[],unlinked_picks:[],errors:{}}));
const el=id=>{if(!elements.has(id))elements.set(id,{value:'',classList:{toggle(){}},textContent:'',innerHTML:''});return elements.get(id)};
const context=vm.createContext({document:{getElementById:el,querySelectorAll:()=>[]},localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},navigator:{},location:{protocol:'http:'},Intl,Date,URL,Blob,console,setTimeout(){},setInterval(fn,ms){timers.push({fn,ms})},fetch:async()=>{throw Error('offline')}});
for(const f of ['research_ui.js','tracker.js','kalshi_ui.js','app.js'])vm.runInContext(fs.readFileSync(f,'utf8'),context);
const run=code=>vm.runInContext(code,context);
assert.equal(run('kalshiFeed'),null,'Malformed cached error container must not become active feed');

(async()=>{
  const feed={schema_version:1,generated_utc:new Date().toISOString(),status:'ok',errors:[],markets:[],unlinked_picks:[]};
  context.testFeed=feed;
  run('kalshiFeed=testFeed;currentView="kalshi";kalshiFeedError="Published Kalshi update unavailable";drawKalshi()');
  assert.match(el('kalshiStatus').innerHTML,/update unavailable/);
  timers.find(t=>t.ms===60000).fn();
  assert.match(el('kalshiStatus').innerHTML,/update unavailable/,'minute redraw must preserve fetch failures');
  run('setView("kalshi")');
  assert.equal(el('kalshi').hidden,false);
  assert.equal(el('today').hidden,true);
  assert.equal(el('slateControls').hidden,true);
  assert.match(el('kalshiStatus').innerHTML,/update unavailable/,'re-entering view preserves cached error');
  await run('refreshKalshi()');
  assert.equal(run('kalshiFeed.generated_utc'),feed.generated_utc);
  assert.match(el('kalshiStatus').innerHTML,/unchanged/);
  const pending=[];
  context.fetch=url=>{assert.match(url,/^\.\/data\/kalshi\.json/);return new Promise(resolve=>pending.push(resolve))};
  const old=run('refreshKalshi()'),fresh=run('refreshKalshi()');
  pending[1]({ok:true,json:async()=>({...feed,generated_utc:new Date(Date.parse(feed.generated_utc)+1000).toISOString(),errors:['new publication']})});await fresh;
  pending[0]({ok:true,json:async()=>({...feed,errors:['old publication']})});await old;
  assert.match(el('kalshiStatus').innerHTML,/new publication/);
  assert.doesNotMatch(el('kalshiStatus').innerHTML,/old publication/);
  assert.equal(run('kalshiFeedError'),null);
  assert(storage.has('matchlab_kalshi_cache_v1'));
  assert(!storage.get('matchlab_kalshi_cache_v1').includes('matchlab_private_bets'));
  run('setView("today")');
  assert.equal(el('kalshi').hidden,true);
  assert.equal(el('slateControls').hidden,false);
  console.log('PASS: Kalshi navigation, failure retention, public-only cache and overlapping refreshes');
})().catch(error=>{console.error(error);process.exitCode=1});
